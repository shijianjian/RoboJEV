# the manifest


def read_manifest(out_dir) -> dict | None:
    """The manifest already in `out_dir`, or None. A corrupt one is None, not an exception: it is
    a file this code wrote and can write again, and refusing to harvest over it helps nobody."""
    path = pathlib.Path(out_dir) / MANIFEST
    if not path.is_file():
        return None
    try:
        found = json.loads(path.read_text())
    except (ValueError, OSError):  # pragma: no cover -- a truncated write
        return None
    return found if isinstance(found, dict) else None


def _own_versions() -> dict:
    """What this package can say about itself: the interpreter and numpy."""
    return {"python": sys.version.split()[0], "numpy": np.__version__}


#: Who fills a manifest's `versions` block. The default is what this package can see of itself;
#: a **host** knows more -- its own commit, its simulator's build, the torch a checkpoint was
#: trained under -- and installs its collector with `use_version_collector` once, at the top of
#: whatever command is harvesting. Provenance is the host's to state, and a model package that
#: imported one to ask would be the dependency this seam exists to remove.
_version_collector = _own_versions


def use_version_collector(collector) -> None:
    """Install the host's own `() -> dict`. Passing `None` restores this package's own."""
    global _version_collector
    _version_collector = collector if collector is not None else _own_versions


def versions() -> dict:
    """The versions a row depends on, best effort.

    A failure must not lose a finished harvest, so a collector that raises degrades to this
    package's own answer rather than to nothing: a caller reading `{python, numpy}` knows exactly
    how much was collected, where an empty dict and a half-filled one look alike.
    """
    try:
        return dict(_version_collector())
    except Exception:  # pragma: no cover -- a host collector that reaches for a missing torch
        return _own_versions()


def now() -> str:
    return datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds")


def bump(counter: dict, key: str, by: int = 1) -> None:
    counter[key] = counter.get(key, 0) + by


def totals(records: dict, pick) -> dict:
    """Sum one per-task counter across every task in the directory, so every aggregate in a
    manifest counts the *directory* and not just the tasks this run happened to rewrite."""
    out: dict[str, int] = {}
    for record in records.values():
        for key, n in pick(record).items():
            bump(out, key, n)
    return out


