"""The shape of a harvest directory: its layout, its manifest, its splits, its row checks.

A harvest writes one `task_<i>.jsonl` per task, a `manifest.json` beside them, and -- when it
renders frames -- a `frames.jsonl` sidecar indexing a `frames/` tree. Everything in this module is
about *that directory* rather than about any one way of filling it: the expert rollout harvester
(`v2.rollout`) and the DAgger round (`dagger`) both write it, both read each other's manifests,
and both have to agree on what a split is, how a row's random stream is seeded, and what a valid
`gold_probs` block looks like. So it is here, once, rather than in whichever harvester happened to
be written first.

Stdlib plus numpy: no simulator, no torch, no network.
"""
from __future__ import annotations

import dataclasses
import datetime
import hashlib
import json
import math
import pathlib
import sys

import numpy as np

from robojev import home

#: The manifest's file name inside the output directory. `robojev train` copies it into the
#: checkpoint, and a server reads the numbers a checkpoint was trained under back out of it.
MANIFEST = "manifest.json"

#: `gold_probs_kind` for every question a harvester writes: each distribution is computed by a
#: rule written down in the harvester rather than sampled, which is exactly what upstream's
#: `programmatic_conditional_distribution` means.
PROBS_KIND = "programmatic_conditional_distribution"

#: The sidecar that pairs a row with the camera frames of its decision point, one JSON object per
#: line keyed by `row_id` (`{"row_id": …, "images": {"agentview": …, "wrist": …}}`).
#:
#: **Not** an `images` key inside the row: upstream's request validator accepts exactly
#: `{id, state, questions}` and nothing establishes that `validate_training_row` is more
#: forgiving. The frames ride beside the rows, so the jsonl the trainer reads stays byte for byte
#: what it expects and nothing about a row's `state` changes.
FRAMES = "frames.jsonl"

#: Where the JPEGs go, under the output directory: `frames/<task>/<demo>/<step>_<camera>.jpg`.
FRAMES_DIR = "frames"

#: The rows are this project's, computed over somebody else's simulator. Recorded per row because a
#: training jsonl is a file that travels on its own, away from this repository.
PROVENANCE = "generated by robojev over LIBERO tasks"

#: `split` values the trainer accepts. Only three of the five are produced; the tuple is the
#: vocabulary, for the row check.
SPLITS = ("train", "dev", "calibration", "test", "ood")


def log_to_stderr(message: str) -> None:
    """Progress goes to stderr, always: `robojev harvest`'s stdout is the manifest path and
    nothing else, the same contract `eval` has for the run directory."""
    print(f"robojev harvest: {message}", file=sys.stderr, flush=True)


def out_root(policy: str, suite: str) -> pathlib.Path:
    """`$ROBOJEV_HOME/data/<policy>/<suite>` -- where a harvest lands by default.

    Under the package's home directory and not the checkout: rows are runtime output, and `data/`
    sits beside the `checkpoints/` that `robojev train` will write from it.
    """
    return home.home() / "data" / policy / suite


# --------------------------------------------------------------------------------------------
# splits


@dataclasses.dataclass(frozen=True)
class Splits:
    """The held-out pair, over the tasks a suite has.

    A *task* split, not a row split: splitting by task is what makes the trainer's no-crossing
    rule true by construction, since every row of a task lands in one split together and no
    near-duplicate scene straddles the boundary.
    """

    tasks: tuple[int, ...] = ()
    dev_task: int | None = None
    test_task: int | None = None


def resolve_splits(splits: Splits, known_tasks=None) -> Splits:
    """Fill `dev_task`/`test_task` when the caller left them unset.

    The default is the last task as `test` and the second-to-last as `dev`. A harvest of fewer
    than three tasks gets **no** held-out task at all: with two tasks the rule would leave `train`
    empty, and the trainer rejects an empty split outright. A one-task proof harvest is a file to
    inspect, not a file to train on, and the manifest says so by carrying `"splits": {"train": [0]}`.

    `known_tasks` is every task the **output directory** holds once this run finishes, which is
    not the same as the tasks being harvested on a partial re-harvest. Re-running task 3 of a
    finished ten-task harvest must label its rows `train` because 8 and 9 are the held-out pair on
    disk; resolving against the run's own task list alone would make task 3 the test split and
    quietly contradict the nine files beside it.
    """
    tasks = tuple(sorted(known_tasks)) if known_tasks is not None else tuple(splits.tasks)
    if splits.dev_task is None and splits.test_task is None and len(tasks) >= 3:
        return dataclasses.replace(splits, dev_task=tasks[-2], test_task=tasks[-1])
    return splits


def split_for(task_index: int, splits: Splits) -> str:
    """`"test"` for the test task, `"dev"` for the dev task, `"train"` otherwise.

    A function of the **task id** and the held-out pair, never of the set being harvested, so a
    run of `--tasks 0,9` gives task 9 the same `test` it would have had in a full run.
    """
    if splits.test_task is not None and task_index == splits.test_task:
        return "test"
    if splits.dev_task is not None and task_index == splits.dev_task:
        return "dev"
    return "train"


# --------------------------------------------------------------------------------------------
# rows


def row_rng(seed: int, task_index: int, episode: int, step: int) -> np.random.Generator:
    """A generator that depends on the row, not on the run.

    `hash()` is salted per process for strings, so it cannot be used: this is a blake2b digest of
    the four numbers, which makes `--tasks 3` alone and `--tasks 0,1,2,3` produce byte-identical
    rows for task 3. That is what lets a harvest be resumed, extended or re-run one task at a
    time, and what makes `--jobs 8` byte-identical to `--jobs 1`.
    """
    key = f"{seed}:{task_index}:{episode}:{step}".encode()
    return np.random.default_rng(int.from_bytes(hashlib.blake2b(key, digest_size=8).digest(), "big"))


def check_probs(row: dict) -> None:
    """Every `gold_probs` distribution covers exactly its question's candidates and sums to 1.

    This is `validate_training_row`'s own rule, asserted where the row is *made*. The trainer
    would catch it too, hours later and on another machine; catching it here means a harvest that
    finishes has produced a file the trainer accepts.
    """
    for qid, probs in row["gold_probs"].items():
        q = row["questions"][qid]
        expected = {"false", "true"} if q["type"] == "boolean" else set(q["criteria"])
        if set(probs) != expected:
            raise AssertionError(f"{row['id']} {qid}: gold_probs covers {sorted(probs)}, "
                                 f"expected {sorted(expected)}")
        total = math.fsum(probs.values())
        if abs(total - 1.0) > 1e-8:
            raise AssertionError(f"{row['id']} {qid}: gold_probs sums to {total!r}, not 1")


